import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, expect, it } from 'vitest'
import App from './App'

beforeEach(() => localStorage.clear())
afterEach(cleanup)

const button = (name: string) => screen.getByRole('button', { name })
const fill = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label), { target: { value } })

it('renders the board without a Pi account and filters seeded tasks', () => {
  render(<App />)
  expect(screen.getByRole('img', { name: 'Pi Tasks' })).toBeTruthy()
  expect(screen.getByText('Demo mode')).toBeTruthy()
  expect(screen.getAllByRole('article')).toHaveLength(6)
  fireEvent.click(button('Design'))
  expect(screen.getAllByRole('article')).toHaveLength(2)
  fill('Search tasks', 'palette')
  expect(screen.getAllByRole('article')).toHaveLength(1)
  expect(button('Create an accessible color palette')).toBeTruthy()
})

it('posts, claims, submits and pays a demo bounty and persists the completed profile', async () => {
  const view = render(<App />)
  fireEvent.click(button('Sign in'))
  fireEvent.click(button('Demo: @maya.design'))
  fireEvent.click(button('Post a task'))
  fill('Title', 'Proofread the welcome guide')
  fill('Description', 'Proofread the first three pages and send a note with corrections.')
  fill('Category', 'Writing')
  fill('Reward (Pi)', '3.5')
  fill('Claim deadline (UTC)', new Date(Date.now() + 86_400_000).toISOString().slice(0, 10))
  fireEvent.click(button('Publish task'))
  expect(screen.getByRole('heading', { name: 'Proofread the welcome guide' })).toBeTruthy()
  expect(screen.queryByRole('button', { name: 'Claim task' })).toBeNull()
  fireEvent.click(button('@maya.design'))
  fireEvent.click(button('Demo: @jordan.codes'))
  fireEvent.click(button('Claim task'))
  fill('Completion note or link', 'All three pages reviewed; no corrections needed.')
  fireEvent.click(button('Mark complete'))
  expect(screen.getByText('Submitted work')).toBeTruthy()
  expect(screen.queryByRole('button', { name: 'Release demo reward' })).toBeNull()
  fireEvent.click(button('@jordan.codes'))
  fireEvent.click(button('Demo: @maya.design'))
  fireEvent.click(button('Release demo reward'))
  expect(await screen.findByText('Demo reward released. No Pi was transferred.')).toBeTruthy()
  view.unmount()
  render(<App />)
  fireEvent.click(button('Sign in'))
  fireEvent.click(button('Demo: @jordan.codes'))
  fireEvent.click(button('My profile'))
  expect(screen.getByText('1 reputation point')).toBeTruthy()
  expect(screen.getByRole('heading', { name: 'Completed work 1' })).toBeTruthy()
  expect(screen.getAllByText('Demo paid')).toHaveLength(2)
})
